import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const workflow = read('.github/workflows/qa.yml');
const runtime = read('scripts/registry-cli-qa/run.mjs');
const pin = read('cli-pin.env');
assert.equal(pin, 'CADENCR_RELEASE_VERSION=0.13.1-dev.39108033875.1\nCADENCR_RELEASE_SHA256=d11bfade6297fa30e1e10e82605f5a221da8e07edeeee372e2c2f6185c6ff725\nCADENCR_RELEASE_TAG=cli/v0.13.1-dev.39108033875.1\n');
assert.equal((workflow.match(/runs-on: ubuntu-24.04/g) ?? []).length, 2);
assert.match(workflow, /fresh:\n    needs: first/);
assert.doesNotMatch(workflow, /actions\/(?:download-artifact|cache)@/);
assert.doesNotMatch(workflow, /include-hidden-files: true|qa-state|qa-private/);
assert.equal((workflow.match(/QA_DEFAULT_BRANCH:/g) ?? []).length, 4);
assert.equal((workflow.match(/QA_SIGNING_KEY_PEM: \$\{\{ secrets.QA_SIGNING_KEY_PEM \}\}/g) ?? []).length, 2);
assert.equal((workflow.match(/persist-credentials: false/g) ?? []).length, 2);
assert.equal((workflow.match(/run: node scripts\/registry-cli-qa\/guard.mjs/g) ?? []).length, 2);
assert.equal((workflow.match(/QA_EXPECTED_INVENTORY_SHA256: \$\{\{ needs.first.outputs.inventory_sha256 \}\}/g) ?? []).length, 2);
assert.ok(runtime.indexOf('assertX8664Elf(binaryBytes)') < runtime.indexOf('writeFileSync(key,'));
assert.ok(runtime.indexOf('initialObservation(') < runtime.indexOf('writeFileSync(key,'));
assert.match(runtime, /let baseline = initialBaseline/);
assert.match(runtime, /archiveCoverage\(JSON.parse\(publicBytes\), plan.archives\)/);
assert.match(runtime, /replayUnchanged\(observed, baseline\)/);
assert.match(runtime, /verify\(index\)/);
assert.match(runtime, /anonymousDiscovery/);
assert.match(workflow, /inventory_sha256: \$\{\{ steps.execution.outputs.inventory_sha256 \}\}/);
console.log('Three-kind QA workflow configuration checks passed');
