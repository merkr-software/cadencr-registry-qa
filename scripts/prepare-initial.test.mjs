import { mkdtempSync, mkdirSync, copyFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const root = mkdtempSync(join(tmpdir(), 'qa-prepare-test-'));
mkdirSync(join(root, 'requests'));
mkdirSync(join(root, 'fixtures'));
copyFileSync(new URL('../fixtures/theme.tar.gz', import.meta.url), join(root, 'fixtures/theme.tar.gz'));
const command = new URL('./prepare-initial.mjs', import.meta.url).pathname;
assert.equal(spawnSync(process.execPath, [command, 'a'.repeat(40), 'qa-source-theme-v0.0.1'], { cwd: root }).status, 0);
const request = JSON.parse(readFileSync(join(root, 'requests/initial.json')));
for (const date of [request.generated_at, request.expires_at]) assert.match(date, /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/);
assert.equal(Date.parse(request.expires_at) - Date.parse(request.generated_at), 7 * 86400000);
const submission = JSON.parse(readFileSync(join(root, 'requests/submission.json')));
assert.equal(submission.package.package.theme.license, 'Apache-2.0');
assert.equal(submission.package.package.theme.id, 'qa-inert-theme');
assert.notEqual(spawnSync(process.execPath, [command, 'a'.repeat(40), 'qa-source-theme-v0.0.1'], { cwd: root }).status, 0, 'must refuse overwrite');
console.log('Preparation tests passed; diagnostic scratch retained:', root);
